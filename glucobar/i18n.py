_lang = None


def detect_language():
    if sys.platform == "win32":
        try:
            import ctypes
            langid = ctypes.windll.kernel32.GetUserDefaultUILanguage()
            return _WINDOWS_PRIMARY.get(langid & 0x3FF, "en")
        except Exception:
            pass
    try:
        name = (locale.getlocale()[0] or "").lower()
    except ValueError:
        name = ""
    return next((code for code in STRINGS if name.startswith(code)), "en")


def set_language(preference):
    """preference: "auto" oppure un codice di LANGUAGES."""
    global _lang
    _lang = preference if preference in STRINGS else detect_language()


def current_language():
    return _lang or detect_language()


def t(key, **kwargs):
    text = STRINGS[current_language()].get(key) or STRINGS["en"][key]
    return text.format(**kwargs) if kwargs else text
