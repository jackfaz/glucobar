_lang = None


def detect_language():
    if sys.platform == "darwin":
        # un'app aperta dal Finder non ha LANG: si chiede a macOS
        try:
            from Foundation import NSLocale
            preferred = [str(lang).lower() for lang in NSLocale.preferredLanguages()]
            for name in preferred:
                code = next((c for c in STRINGS if name.startswith(c)), None)
                if code:
                    return code
        except Exception:
            pass
    if sys.platform == "win32":
        try:
            import ctypes
            langid = ctypes.windll.kernel32.GetUserDefaultUILanguage()
            return _WINDOWS_PRIMARY.get(langid & 0x3FF, "en")
        except Exception:
            pass
    try:
        name = (locale.getlocale()[0] or "").lower()
    except ValueError:
        name = ""
    return next((code for code in STRINGS if name.startswith(code)), "en")


def set_language(preference):
    """preference: "auto" oppure un codice di LANGUAGES."""
    global _lang
    _lang = preference if preference in STRINGS else detect_language()


def current_language():
    return _lang or detect_language()


def element_name(element):
    """Nome di un elemento da mostrare; sul Mac l'"icona" sta nella barra dei menu."""
    if element == "tray" and sys.platform == "darwin":
        return t("mode_tray_mac")
    return t(f"mode_{element}")


def refresh_label(seconds):
    """60 -> "1 min", 30 -> "30 s", 90 -> "90 s": uguale in tutte le lingue."""
    seconds = int(seconds)
    return f"{seconds // 60} min" if seconds >= 60 and seconds % 60 == 0 else f"{seconds} s"


def t(key, **kwargs):
    text = STRINGS[current_language()].get(key) or STRINGS["en"][key]
    return text.format(**kwargs) if kwargs else text
